"""剪贴板后端抽象：Windows / macOS 共用的**冻结契约**。

这个文件是两端并行开发的分界线：所有平台差异都必须收敛到 `poll()` / `write()`
两个方法里面，上层（`sync/engine.py`）拿到的永远是平台无关的 `ClipItem`。

⚠️ 本文件由 **macOS 端** 维护，Windows 端**只读**。要加字段先改 `docs/CLIPBOARD-SYNC-CONTRACT.md`
第 3 节，两端同时改，否则另一端会 `AttributeError`（`tests/test_clipboard_contract.py` 会拦）。

设计上的三条硬约定（省掉大量联调）：

1. **轮询统一**：两端都实现 `poll()`，由上层以固定间隔调用（默认 150ms）。
   macOS 没有剪贴板变更事件（`QClipboard.dataChanged` 实测不触发），必须轮询 `changeCount`；
   Windows 虽然能收 `WM_CLIPBOARDUPDATE`，但为保持一致也走轮询（Windows 侧读
   `GetClipboardSequenceNumber`，开销可忽略）。**上层只有一条代码路径。**
2. **去重下沉**：`poll()` 只在内容**真的变了**时返回 `ClipItem`，相同内容连续调用返回 `None`。
   上层不需要自己记上次读到了什么。
3. **自写吞掉**：`write()` 之后，紧接着由这次写入引发的变更，`poll()` **必须返回 `None`**。
   这是环抑制的第一道闸（第二道是引擎层的内容指纹）。两端各自用平台的序号实现：
   macOS 记 `changeCount`，Windows 记 `GetClipboardSequenceNumber`。
"""

from __future__ import annotations

import hashlib
import logging
import os
import sys
import time
from dataclasses import dataclass, field, replace
from typing import Literal, Protocol, runtime_checkable

log = logging.getLogger(__name__)

ClipKind = Literal["text", "image", "mixed"]

#: 单张图片上限（PNG 字节数）。超过则 `poll()` 直接跳过并记 warning：
#: Retina 全屏截图约 8–15MB，再大基本是误复制了整个图层的工程文件。
MAX_IMAGE_BYTES = 32 * 1024 * 1024
#: 纯文本上限（UTF-8 字节数）。防止把整个日志文件拖进网络。
MAX_TEXT_BYTES = 2 * 1024 * 1024

#: 剪贴板里出现这些类型名，说明内容来自密码管理器 / 系统认为不该被监听。
#: 两端各自匹配自己平台的标记，命中就整条跳过（不传输、不过滤内容）。
SKIP_MARKERS_MACOS = (
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
)
SKIP_MARKERS_WINDOWS = (
    "ExcludeClipboardContentFromMonitorProcessing",
    "CanIncludeInClipboardHistory",
    "CanUploadToCloudClipboard",
)


class ClipboardError(RuntimeError):
    """剪贴板不可用（权限缺失、被其它进程占用、平台不支持）。"""


# --------------------------------------------------------------------------- #
# 数据模型
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class ImageData:
    """一张图片的规范化表示。

    约定：**一律 PNG**。不要传 TIFF / DIB / QImage —— 这三样跨平台都不可移植：
      · Qt 写剪贴板只写 `public.tiff`（实测无 png），读只给 `application/x-qt-image`；
      · Windows 原生是 `CF_DIB`（BGR、行倒序、无 alpha），必须转 PNG。
    转换在各自的 `clipboard/{macos,windows}.py` 里做完，上层只认 PNG。
    """

    png: bytes
    width: int = 0
    height: int = 0

    @property
    def size(self) -> int:
        return len(self.png)


@dataclass(frozen=True)
class ClipItem:
    """一条剪贴板内容。不可变，可安全跨线程传递。"""

    kind: ClipKind
    text: str | None = None
    html: str | None = None
    image: ImageData | None = None
    ts: float = field(default_factory=time.time)
    source: str = ""          # 来源主机：windows / mac / remote
    digest: str = ""          # 空则由 __post_init__ 计算
    # ---- 来源应用（可选，v2 剪贴板列表要显示「Mac · 微信」）----
    app: str = ""             # 应用显示名（截图 = "截图"）
    app_id: str = ""          # 应用 bundle id（本机取图标用；跨端传了也无妨）
    # ---- 文件来源（可选）----
    path: str = ""            # 来自本机文件的原始路径；**只在本机有意义，不上网**
    file_size: int = 0        # 文件本身的字节数（列表显示用；文件不同步，也不参与容量统计）

    def __post_init__(self) -> None:
        if not self.digest:
            object.__setattr__(self, "digest", self.compute_digest())
        # 轻量自洽校验：kind 与内容必须对得上，早失败好过联调时才发现
        has_text = bool(self.text)
        has_image = self.image is not None
        if self.kind == "text" and not has_text:
            raise ValueError("kind=text 但 text 为空")
        if self.kind == "image" and not has_image:
            raise ValueError("kind=image 但 image 为空")
        if self.kind == "mixed" and not (has_text and has_image):
            raise ValueError("kind=mixed 需要同时有 text 和 image")

    def compute_digest(self) -> str:
        """内容指纹。用于跨端去重与环抑制，**不含 ts / source**（否则永远不相等）。"""
        h = hashlib.sha256()
        if self.text:
            h.update(b"t:")
            h.update(self.text.encode("utf-8", "replace"))
        if self.html:
            h.update(b"\x00h:")
            h.update(self.html.encode("utf-8", "replace"))
        if self.image is not None:
            h.update(b"\x00i:")
            h.update(self.image.png)
        if self.path:
            # 同名文件在不同目录是两条内容，指纹必须带上路径
            h.update(b"\x00p:")
            h.update(self.path.encode("utf-8", "replace"))
        return h.hexdigest()

    # ---- 诊断用 ----
    def describe(self) -> str:
        if self.kind == "mixed":
            return f"图文混合（{len(self.text or '')} 字 + {self.image.size // 1024}KB 图）"
        if self.kind == "image":
            return f"图片 {self.image.width}×{self.image.height}，{self.image.size // 1024}KB"
        return f"文本 {len(self.text or '')} 字"

    def wire_size(self) -> int:
        """上网络的字节数（不含帧头）。用于判断"这条要不要走后台慢传"。"""
        n = len((self.text or "").encode("utf-8", "replace"))
        n += len((self.html or "").encode("utf-8", "replace"))
        if self.image is not None:
            n += self.image.size
        return n


def make_text(text: str, *, html: str | None = None, source: str = "") -> ClipItem:
    """把一段文本包成 ClipItem（超限则截断并记警告，而不是抛异常——剪贴板不该让程序崩）。"""
    raw = text.encode("utf-8", "replace")
    if len(raw) > MAX_TEXT_BYTES:
        log.warning("文本过大（%d 字节），截断到 %d", len(raw), MAX_TEXT_BYTES)
        text = raw[:MAX_TEXT_BYTES].decode("utf-8", "ignore")
    return ClipItem(kind="text", text=text, html=html, source=source)


def make_file(
    path: str,
    *,
    png: bytes | None = None,
    width: int = 0,
    height: int = 0,
    source: str = "",
    app: str = "",
    app_id: str = "",
    size: int = 0,
) -> ClipItem | None:
    """访达里复制的**文件**包成 ClipItem。

    · 图片文件（传了 `png`）→ `kind="mixed"`：图片内容照常跨端，`text` 是文件名；
    · 其它文件 → `kind="text"`：`text` 是文件名，**不上网**（文件本身同步不了），
      引擎见到 `path` 且没有图片就只在本机留一条。
    """
    name = os.path.basename(path) or path
    if png:
        item = make_image(png, width, height, text=name, source=source)
    else:
        item = make_text(name, source=source)
    if item is None:
        return None
    return replace(item, path=path, file_size=size, app=app, app_id=app_id)


PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def png_size(png: bytes) -> tuple[int, int]:
    """从 PNG 的 IHDR 里读 `(宽, 高)`；不是 PNG / 太短就返回 `(0, 0)`。

    以前只有各平台后端在解码时填宽高，`make_image(png)` 的默认值是 0×0，
    于是 `clip send --image` / `tools/*_serve.py --send-image` 发出去的帧宽高是 0，
    对端预览窗按比例布局会直接退化（BUG-005）。尺寸本来就在 PNG 头里，不该靠调用方记得传。
    """
    if len(png) < 24 or not png.startswith(PNG_SIGNATURE) or png[12:16] != b"IHDR":
        return (0, 0)
    width = int.from_bytes(png[16:20], "big")
    height = int.from_bytes(png[20:24], "big")
    if width <= 0 or height <= 0:
        return (0, 0)
    return (width, height)


def make_image(png: bytes, width: int = 0, height: int = 0, *, text: str | None = None,
               source: str = "") -> ClipItem | None:
    """把 PNG 包成 ClipItem。超限返回 None（调用方跳过即可，不要抛）。

    `width/height` 传 0（或不传）时自动从 PNG 头解析 —— 见 `png_size()`。
    """
    if not png:
        return None
    if len(png) > MAX_IMAGE_BYTES:
        log.warning("图片过大（%.1fMB > %dMB），跳过", len(png) / 1048576, MAX_IMAGE_BYTES // 1048576)
        return None
    if width <= 0 or height <= 0:
        width, height = png_size(png)
    img = ImageData(png=png, width=width, height=height)
    if text:
        return ClipItem(kind="mixed", text=text, image=img, source=source)
    return ClipItem(kind="image", image=img, source=source)



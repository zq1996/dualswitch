# 工厂
# --------------------------------------------------------------------------- #
def create_backend(kind: str = "auto") -> ClipboardBackend:
    """按配置创建后端。

    kind: auto | macos | windows | mock | none
    auto 按 `sys.platform` 选；导入或初始化失败时**降级为 NullBackend 并记 error**，
    绝不抛异常 —— 剪贴板坏了不能连累切屏这个主功能。
    """
    kind = (kind or "auto").strip().lower()
    if kind == "none":
        return NullBackend()
    if kind == "mock":
        from .mock import MockBackend

        return MockBackend()

    if kind == "auto":
        kind = "windows" if sys.platform == "win32" else "macos"

    try:
        if kind == "macos":
            from .macos import MacClipboardBackend

            return MacClipboardBackend()
        if kind == "windows":
            from .windows import WindowsClipboardBackend

            return WindowsClipboardBackend()
    except ImportError as exc:
        # 平台后端还没写（并行开发时另一端的正常状态）—— 用 info，不要用 error 吓人
        log.info("剪贴板后端 %s 尚未实现（%s），同步功能暂时关闭", kind, exc)
        return NullBackend()
    except Exception as exc:  # noqa: BLE001 - 后端不可用属于预期内的降级
        log.error("剪贴板后端 %s 初始化失败，同步功能已关闭：%s", kind, exc)
        return NullBackend()

    log.error("未知的剪贴板后端 %r，同步功能已关闭", kind)
    return NullBackend()

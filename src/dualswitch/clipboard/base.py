@runtime_checkable
class ClipboardBackend(Protocol):
    """平台后端必须实现的三个方法。实现见 `clipboard/macos.py` / `clipboard/windows.py`。"""

    name: str

    def poll(self) -> ClipItem | None:
        """读一次剪贴板。

        - 内容与上次返回的**完全相同** → 返回 None（去重下沉）
        - 内容空 / 只含不支持的类型 / 命中 SKIP_MARKERS → 返回 None
        - 图片超过 MAX_IMAGE_BYTES → 返回 None（记 warning）
        - `write()` 之后的第一次调用（自写回弹）→ 返回 None
        """
        ...

    def write(self, item: ClipItem) -> None:
        """把内容写到系统剪贴板。

        必须保证写入后本地能**直接粘贴**：文本要带 plain text，图片要带 PNG
        （macOS 还要补 TIFF，Windows 还要补 CF_DIB，否则部分应用粘不出来）。
        实现内部要记录写后的平台序号，供 `poll()` 吞掉自写回弹。
        """
        ...

    def probe(self) -> dict[str, str]:
        """自检信息，`dualswitch doctor` 和 `tools/clip_selftest.py` 会打印。

        建议包含：平台、可用类型列表、上次变更序号、最近一次读到的 kind。
        不要在这里做耗时操作（<50ms），它会被 UI 状态轮询调用。
        """
        ...

    def close(self) -> None:
        ...


class NullBackend:
    """没有可用后端时的降级实现：同步功能自动关闭，其余功能不受影响。"""

    name = "none"

    def poll(self) -> ClipItem | None:
        return None

    def write(self, item: ClipItem) -> None:
        raise ClipboardError("当前环境没有可用的剪贴板后端")

    def probe(self) -> dict[str, str]:
        return {"backend": "none", "reason": "未找到可用的剪贴板后端"}

    def close(self) -> None:
        pass


